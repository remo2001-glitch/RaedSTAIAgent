"""QQ2 (b98، رحال 2026-11-20): صيغة العدّ العربية الموحّدة لرسائل البوت.
1 ⇒ «صفقة واحدة»، 2 ⇒ «صفقتان»، 3–10 ⇒ «4 صفقات»، 0 و11+ ⇒ «0 صفقات» / «11 صفقة» (والمذكّر المنصوب «11 سجلاً»)."""

# المفرد، المثنى، الجمع (3–10)، التمييز (11+)
FORMS = {
    "سجل": ("سجل واحد", "سجلان", "سجلات", "سجلاً"),
    "صفقة": ("صفقة واحدة", "صفقتان", "صفقات", "صفقة"),
    "إشارة": ("إشارة واحدة", "إشارتان", "إشارات", "إشارة"),
    "عملة": ("عملة واحدة", "عملتان", "عملات", "عملة"),
    "أصل": ("أصل واحد", "أصلان", "أصول", "أصلاً"),
    "مركز": ("مركز واحد", "مركزان", "مراكز", "مركزاً"),
    "شمعة": ("شمعة واحدة", "شمعتان", "شموع", "شمعة"),
    "مرة": ("مرة واحدة", "مرتين", "مرات", "مرة"),
    "ساعة": ("ساعة واحدة", "ساعتين", "ساعات", "ساعة"),
    "يوم": ("يوم واحد", "يومين", "أيام", "يوماً"),
}


def ar_n(n, word: str) -> str:
    """العدد مع معدوده بصيغته الصحيحة؛ كلمة غير معروفة ⇒ «n كلمة» كما هي."""
    try:
        k = int(n)
    except (TypeError, ValueError):
        return f"{n} {word}"
    f = FORMS.get(word)
    if not f:
        return f"{k} {word}"
    if k == 1:
        return f[0]
    if k == 2:
        return f[1]
    if k == 0 or 3 <= k % 100 <= 10:
        return f"{k} {f[2]}"
    return f"{k} {f[3]}"
